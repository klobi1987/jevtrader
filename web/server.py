"""JevTrader Real-Time Web Dashboard Server.

Serves static UI assets and live REST endpoints for Cockpit telemetry,
orderbook confluence scanner, and SQLite trade history.
"""

import os
import sys
import json
import sqlite3
import argparse
import mimetypes
from pathlib import Path
from http.server import HTTPServer, SimpleHTTPRequestHandler, ThreadingHTTPServer

BASE_DIR = Path(__file__).resolve().parent.parent
PUBLIC_DIR = Path(__file__).resolve().parent / "public"
DATA_DIR = BASE_DIR / "data"
DB_PATH = DATA_DIR / "jevtrader.sqlite3"
STATE_PATH = DATA_DIR / "dashboard_state.json"

class DashboardHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(PUBLIC_DIR), **kwargs)

    def do_GET(self):
        url = self.path.split("?")[0]

        # REST API endpoints
        if url == "/api/state":
            self._handle_get_state()
        elif url == "/api/trades":
            self._handle_get_trades()
        elif url == "/api/decisions":
            self._handle_get_decisions()
        elif url == "/api/health":
            self._send_json({"status": "ok", "app": "JevTrader Dashboard"})
        else:
            # Fallback to index.html for root or unknown route
            if url == "/" or not (PUBLIC_DIR / url.lstrip("/")).exists():
                self.path = "/index.html"
            return super().do_GET()

    def _handle_get_state(self):
        """Returns live dashboard state generated by JevTrader engine."""
        if STATE_PATH.exists():
            try:
                with open(STATE_PATH, "r", encoding="utf-8") as f:
                    data = json.load(f)
                self._send_json(data)
                return
            except Exception as e:
                pass

        # Fallback state if state file is still initializing
        fallback = {
            "timestamp": 0,
            "equity": 107.0,
            "free_margin": 107.0,
            "used_margin": 0.0,
            "total_realized_pnl": 0.0,
            "consecutive_losses": 0,
            "circuit_breaker_active": False,
            "circuit_breaker_seconds_left": 0,
            "regime": "SCANNING",
            "breadth_pct": 0.0,
            "pairs_above_vwap": 0,
            "total_pairs": 804,
            "btc_price": 0.0,
            "btc_change_24h_pct": 0.0,
            "btc_impulse_15m": 0.0,
            "system": {
                "mode": "LIVE",
                "entry_model": "liquid/d1-ultra",
                "watchdog_model": "liquid/d1-ultra",
                "exit_mode": "ratchet_trail",
                "max_positions": 8,
                "risk_per_trade_pct": 3.5,
                "max_same_direction": 3
            },
            "active_positions": [],
            "evaluated_candidates": []
        }
        self._send_json(fallback)

    def _handle_get_trades(self):
        """Fetches last 50 closed/active trades from SQLite."""
        if not DB_PATH.exists():
            self._send_json({"trades": []})
            return

        try:
            conn = sqlite3.connect(str(DB_PATH))
            conn.row_factory = sqlite3.Row
            cur = conn.execute("""
                SELECT trade_id, symbol, direction, entry_price, stop_loss, tp1, tp2, 
                       qty_entry, initial_risk_usd, status, is_tp1_filled, is_be_locked,
                       created_ms, updated_ms
                FROM trades 
                ORDER BY updated_ms DESC 
                LIMIT 50
            """)
            trades = [dict(r) for r in cur.fetchall()]
            conn.close()
            self._send_json({"trades": trades})
        except Exception as e:
            self._send_json({"error": str(e), "trades": []}, status=500)

    def _handle_get_decisions(self):
        """Fetches last 30 AI Decision records from OpenRouter audit table."""
        if not DB_PATH.exists():
            self._send_json({"decisions": []})
            return

        try:
            conn = sqlite3.connect(str(DB_PATH))
            conn.row_factory = sqlite3.Row
            cur = conn.execute("""
                SELECT decision_id, symbol, direction, model_name, action_prob, wall_prob,
                       cost_usd, latency_sec, created_ms
                FROM decisions 
                ORDER BY created_ms DESC 
                LIMIT 30
            """)
            decisions = [dict(r) for r in cur.fetchall()]
            conn.close()
            self._send_json({"decisions": decisions})
        except Exception as e:
            self._send_json({"error": str(e), "decisions": []}, status=500)

    def _send_json(self, payload: dict, status: int = 200):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "no-cache, no-store, must-revalidate")
        self.end_headers()
        self.wfile.write(body)

    def end_headers(self):
        self.send_header("Access-Control-Allow-Origin", "*")
        super().end_headers()

def run_server(host: str = "0.0.0.0", port: int = 8088):
    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)
    server_address = (host, port)
    httpd = ThreadingHTTPServer(server_address, DashboardHandler)
    print(f"==================================================")
    print(f"  JEVTRADER WEB COCKPIT LISTENING ON http://{host}:{port}")
    print(f"==================================================")
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down web server...")
        httpd.server_close()

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="JevTrader Web Dashboard Server")
    parser.add_argument("--host", default="0.0.0.0", help="Host to bind (default: 0.0.0.0)")
    parser.add_argument("--port", type=int, default=int(os.getenv("PORT", "8088")), help="Port to bind (default: 8088)")
    args = parser.parse_args()
    run_server(host=args.host, port=args.port)
